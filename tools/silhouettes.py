"""Sagome dei livelli boss di Outflow (disegnate da noi con forme geometriche semplici).

Coordinate di disegno: x da -1 (sinistra) a 1 (destra), y da -1.4 (basso) a 1.4 (alto).
Ogni sagoma e' una funzione (x, y) -> True se il punto e' dentro.
"""


# ---------------------------------------------------------------- primitive
def E(cx, cy, rx, ry):
    return lambda x, y: ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1


def C(cx, cy, r):
    return E(cx, cy, r, r)


def R(x0, y0, x1, y1):
    return lambda x, y: x0 <= x <= x1 and y0 <= y <= y1


def P(*pts):
    def f(x, y):
        inside = False
        n = len(pts)
        for i in range(n):
            x1, y1 = pts[i]
            x2, y2 = pts[(i + 1) % n]
            if (y1 > y) != (y2 > y):
                xi = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
                if x < xi:
                    inside = not inside
        return inside
    return f


def U(*fs):
    return lambda x, y: any(f(x, y) for f in fs)


def D(a, *bs):
    return lambda x, y: a(x, y) and not any(b(x, y) for b in bs)


def I(a, b):
    return lambda x, y: a(x, y) and b(x, y)


ABOVE = lambda y0: (lambda x, y: y >= y0)
BELOW = lambda y0: (lambda x, y: y <= y0)
RIGHT = lambda x0: (lambda x, y: x >= x0)


