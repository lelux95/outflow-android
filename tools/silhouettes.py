def silhouette_mask(name, w, h):
    """Celle (x, y) della griglia w x h dentro la sagoma. Le isole piu' piccole di 4 celle vengono tolte."""
    f = SIL[name][2]
    a = h / w
    cells = set()
    for gy in range(h):
        for gx in range(w):
            x = (gx + 0.5) / w * 2 - 1
            y = (1 - (gy + 0.5) / h * 2) * a
            # la sagoma e' disegnata per un rapporto 1.4: si scala per stare nella griglia
            if f(x * 1.0, y * 1.4 / a):
                cells.add((gx, gy))
    # togli le isole minuscole
    seen, out = set(), set()
    for c in cells:
        if c in seen:
            continue
        comp, stack = [], [c]
        seen.add(c)
        while stack:
            cx, cy = stack.pop()
            comp.append((cx, cy))
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                n = (cx + dx, cy + dy)
                if n in cells and n not in seen:
                    seen.add(n)
                    stack.append(n)
        if len(comp) >= 4:
            out.update(comp)
    return out
